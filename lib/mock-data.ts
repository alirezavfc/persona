export const findUser = (id: string) =>
  users.find((user) => user.id.toLowerCase() === id.toLowerCase());
export const findPost = (id: string) => posts.find((post) => post.id === id);
export const repliesFor = (post: PersonaPost) =>
  post.replyIds
    .map(findPost)
    .filter((reply): reply is PersonaPost => Boolean(reply));
